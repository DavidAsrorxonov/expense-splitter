import fs from "node:fs";
import { openDatabase } from "../src/db/connection";

const db = openDatabase(process.env.DATABASE_PATH ?? "data/app.db");

const group = db.prepare("SELECT id FROM groups LIMIT 1").get() as
  | {
      id: string;
    }
  | undefined;

if (!group) {
  db.close();
  throw new Error(
    "Query plans require a seeded database with at least one group.",
  );
}

const queries: {
  name: string;
  sql: string;
  params: (string | number)[];
  note?: string;
}[] = [
  {
    name: "Active members of a group",
    sql: "SELECT * FROM members WHERE group_id = ? AND archived_at IS NULL",
    params: [group.id],
  },
  {
    name: "Expense list, newest first",
    sql: `SELECT * FROM expenses
          WHERE group_id = ? AND archived_at IS NULL
          ORDER BY spent_on DESC`,
    params: [group.id],
  },
  {
    name: "Monthly totals",
    sql: `SELECT strftime('%Y-%m', spent_on) AS month, SUM(amount_minor)
          FROM expenses WHERE group_id = ? AND archived_at IS NULL
          GROUP BY month`,
    params: [group.id],
  },
  {
    name: "All splits for one member",
    sql: "SELECT * FROM splits WHERE member_id = ?",
    params: [1],
  },
  {
    name: "Settlements of a group, newest first",
    sql: "SELECT * FROM settlements WHERE group_id = ? ORDER BY created_at DESC",
    params: [group.id],
  },
  {
    name: "Balances of a group (view)",
    sql: "SELECT * FROM member_balances WHERE group_id = ?",
    params: [group.id],
  },
  {
    name: "Full-text expense search",
    sql: `SELECT e.id, e.group_id, e.paid_by, e.amount_minor, e.note,
                 e.spent_on, e.created_at, e.archived_at
          FROM expenses_fts
          JOIN expenses e ON e.id = expenses_fts.rowid
          WHERE expenses_fts MATCH ?
            AND e.group_id = ?
            AND (? = 1 OR e.archived_at IS NULL)
          ORDER BY bm25(expenses_fts), e.spent_on DESC, e.id DESC
          LIMIT ?`,
    params: ['"gro"*', group.id, 0, 50],
    note: 'Parameters: MATCH `"gro"*`, the seeded group ID, includeArchived = 0, limit = 50. The virtual-table scan uses the FTS MATCH index (`0:M1`), then looks up matching expenses by primary key. The temporary B-tree sorts matches by relevance, date, and ID; this is not a full scan of the expenses table.',
  },
  {
    name: "Archived expenses, newest first",
    sql: `SELECT id, group_id, paid_by, amount_minor, note,
                 spent_on, created_at, archived_at
          FROM expenses
          WHERE group_id = ? AND archived_at IS NOT NULL
          ORDER BY spent_on DESC, id DESC`,
    params: [group.id],
    note: "Uses idx_expenses_group_spent_on to select the group and return newest-first rows, filtering archived_at within that group. No additional index is indicated by this plan.",
  },
  {
    name: "All splits for a group",
    sql: `SELECT s.expense_id, s.member_id, s.share_minor
          FROM splits s
          JOIN expenses e ON e.id = s.expense_id
          WHERE e.group_id = ?
          ORDER BY s.expense_id, s.member_id`,
    params: [group.id],
    note: "Uses the covering group/date index to find expenses, then the splits composite primary-key index to find their shares. The temporary B-tree orders the result by expense and member; neither table requires a full scan for this query.",
  },
];

const fence = "`".repeat(3);
let md =
  "# Query plans\n\nGenerated by `npm run plans` against a scratch database populated by `npm run seed`, with `DATABASE_PATH` set to the same temporary file for both commands. The application database is not used.\n\nThese plans describe index usage on the small seed dataset, not production-scale timing. No new index was needed for the three Phase 4 queries.\n";

for (const { name, sql, params, note } of queries) {
  const plan = db.prepare(`EXPLAIN QUERY PLAN ${sql}`).all(...params) as {
    detail: string;
  }[];
  const lines = plan.map((row) => row.detail).join("\n");
  console.log(`\n== ${name} ==\n${lines}`);
  md += `\n## ${name}\n\n${fence}sql\n${sql.replace(/\s+/g, " ")}\n${fence}\n\n${fence}text\n${lines}\n${fence}\n`;
  if (note) md += `\n${note}\n`;
}

fs.writeFileSync("docs/query-plans.md", md);
db.close();
console.log("\nWrote docs/query-plans.md");
